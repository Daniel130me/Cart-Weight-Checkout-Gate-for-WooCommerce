<?php
/**
 * Server-side checkout and payment enforcement.
 *
 * @package CartWeightCheckoutGate
 */

namespace CartWeightCheckoutGate;

use Exception;
use WC_Cart;
use WC_Order;
use WP_Error;

defined( 'ABSPATH' ) || exit;

final class Checkout_Validator {
	const ERROR_CODE = 'cwcgfw_minimum_cart_weight';

	/** @var Settings */
	private $settings;

	/** @var Weight_Calculator */
	private $calculator;

	/**
	 * @param Settings          $settings   Settings service.
	 * @param Weight_Calculator $calculator Weight calculator.
	 */
	public function __construct( Settings $settings, Weight_Calculator $calculator ) {
		$this->settings   = $settings;
		$this->calculator = $calculator;
	}

	/** Register all checkout surfaces and defense-in-depth checks. */
	public function register() {
		add_action( 'woocommerce_check_cart_items', array( $this, 'validate_active_cart' ), 20 );
		add_action( 'woocommerce_after_checkout_validation', array( $this, 'validate_classic_checkout' ), 20, 2 );
		add_action( 'woocommerce_store_api_cart_errors', array( $this, 'validate_store_api_cart' ), 20, 2 );
		add_action( 'woocommerce_checkout_create_order', array( $this, 'enforce_before_order_creation' ), 1, 2 );
		add_action( 'woocommerce_before_pay_action', array( $this, 'enforce_before_classic_payment' ), 1 );
		add_action( 'woocommerce_checkout_validate_order_before_payment', array( $this, 'validate_order_before_store_api_payment' ), 20, 2 );
		add_filter( 'woocommerce_locate_template', array( $this, 'locate_minimum_weight_cart_errors_template' ), 20, 3 );
	}

	/** Add a classic WooCommerce notice when the active cart is below the limit. */
	public function validate_active_cart() {
		if ( ! $this->settings->is_enabled() || ! function_exists( 'WC' ) || ! WC()->cart || WC()->cart->is_empty() ) {
			return;
		}

		$status = $this->calculator->get_status( $this->calculator->get_cart_weight_kg( WC()->cart ) );

		if ( $status['reached'] ) {
			return;
		}

		$message = $this->get_cart_error_message( $status );

		if ( ! function_exists( 'wc_has_notice' ) || ! wc_has_notice( $message, 'error' ) ) {
			wc_add_notice(
				$message,
				'error',
				array( 'cwcgfw_minimum_weight' => true )
			);
		}
	}

	/**
	 * Replace WooCommerce's generic cart-error copy only when every checkout
	 * error was generated by this plugin. Other checkout problems retain the
	 * standard WooCommerce template and wording.
	 *
	 * @param string $template      Located template path.
	 * @param string $template_name Requested template name.
	 * @param string $template_path WooCommerce template path.
	 * @return string
	 */
	public function locate_minimum_weight_cart_errors_template( $template, $template_name, $template_path ) {
		unset( $template_path );

		if ( 'checkout/cart-errors.php' !== $template_name || ! $this->settings->is_enabled() ) {
			return $template;
		}

		$error_notices = wc_get_notices( 'error' );
		if ( empty( $error_notices ) ) {
			return $template;
		}

		foreach ( $error_notices as $notice ) {
			if ( empty( $notice['data']['cwcgfw_minimum_weight'] ) ) {
				return $template;
			}
		}

		return CWCGFW_PATH . 'templates/checkout/cart-errors.php';
	}

	/**
	 * Add a structured error during classic checkout validation.
	 *
	 * @param array    $data   Posted checkout data.
	 * @param WP_Error $errors Checkout errors.
	 */
	public function validate_classic_checkout( $data, $errors ) {
		unset( $data );

		if ( ! $errors instanceof WP_Error || ! $this->settings->is_enabled() || ! WC()->cart ) {
			return;
		}

		$status = $this->calculator->get_status( $this->calculator->get_cart_weight_kg( WC()->cart ) );

		$message = $this->get_cart_error_message( $status );

		if (
			! $status['reached'] &&
			! $errors->get_error_message( self::ERROR_CODE ) &&
			( ! function_exists( 'wc_has_notice' ) || ! wc_has_notice( $message, 'error' ) )
		) {
			$errors->add( self::ERROR_CODE, $message );
		}
	}

	/**
	 * Add a Store API cart error for Cart/Checkout Blocks and agentic checkout.
	 *
	 * @param WP_Error $errors Store API errors.
	 * @param WC_Cart  $cart   Store API cart.
	 */
	public function validate_store_api_cart( $errors, $cart ) {
		if ( ! $errors instanceof WP_Error || ! $cart instanceof WC_Cart || ! $this->settings->is_enabled() || $cart->is_empty() ) {
			return;
		}

		$status = $this->calculator->get_status( $this->calculator->get_cart_weight_kg( $cart ) );

		if ( ! $status['reached'] ) {
			$errors->add( self::ERROR_CODE, $this->get_cart_error_message( $status ) );
		}
	}

	/**
	 * Final invariant before WooCommerce persists a checkout order.
	 *
	 * @param WC_Order $order Checkout order object.
	 * @param array    $data  Posted checkout data.
	 * @throws Exception When the cart no longer satisfies the minimum.
	 */
	public function enforce_before_order_creation( $order, $data ) {
		unset( $data );

		if ( ! $order instanceof WC_Order || ! $this->settings->is_enabled() || ! WC()->cart ) {
			return;
		}

		$weight = $this->calculator->get_cart_weight_kg( WC()->cart );
		$status = $this->calculator->get_status( $weight );

		if ( ! $status['reached'] ) {
			throw new Exception( esc_html( wp_strip_all_tags( $this->get_cart_error_message( $status ) ) ) );
		}

		// Persist a trusted snapshot for secure payment-link validation later.
		$order->update_meta_data( Weight_Calculator::ORDER_WEIGHT_META, wc_format_decimal( $weight, 6 ) );
	}

	/**
	 * Block the classic order-pay endpoint for an underweight existing order.
	 *
	 * @param WC_Order $order Order being paid.
	 * @throws Exception When the order is below the current minimum.
	 */
	public function enforce_before_classic_payment( $order ) {
		if ( ! $order instanceof WC_Order || ! $this->settings->is_enabled() ) {
			return;
		}

		$status = $this->calculator->get_status( $this->calculator->get_order_weight_kg( $order ) );

		if ( ! $status['reached'] ) {
			throw new Exception( esc_html( wp_strip_all_tags( $this->get_order_error_message( $status ) ) ) );
		}
	}

	/**
	 * Block Store API payment for an underweight order.
	 *
	 * @param WC_Order $order  Order being paid.
	 * @param WP_Error $errors Payment validation errors.
	 */
	public function validate_order_before_store_api_payment( $order, $errors ) {
		if ( ! $order instanceof WC_Order || ! $errors instanceof WP_Error || ! $this->settings->is_enabled() ) {
			return;
		}

		$status = $this->calculator->get_status( $this->calculator->get_order_weight_kg( $order ) );

		if ( ! $status['reached'] ) {
			$errors->add( self::ERROR_CODE, $this->get_order_error_message( $status ) );
		}
	}

	/** @param array<string, float|bool> $status Weight status. */
	private function get_cart_error_message( $status ) {
		return sprintf(
			/* translators: 1: current cart weight, 2: required minimum, 3: remaining weight, all in kilograms. */
			__( 'Your cart weighs %1$s kg. A minimum of %2$s kg is required before checkout. Please add %3$s kg more.', 'cart-weight-checkout-gate-for-woocommerce' ),
			$this->format_weight( $status['current'] ),
			$this->format_weight( $status['minimum'] ),
			$this->format_weight( $status['remaining'] )
		);
	}

	/** @param array<string, float|bool> $status Weight status. */
	private function get_order_error_message( $status ) {
		return sprintf(
			/* translators: 1: order weight, 2: required minimum, 3: remaining weight, all in kilograms. */
			__( 'Payment is unavailable because this order weighs %1$s kg and the minimum is %2$s kg. Please contact the store or add %3$s kg more through the cart.', 'cart-weight-checkout-gate-for-woocommerce' ),
			$this->format_weight( $status['current'] ),
			$this->format_weight( $status['minimum'] ),
			$this->format_weight( $status['remaining'] )
		);
	}

	/** @param float $weight Weight in kilograms. */
	private function format_weight( $weight ) {
		return wc_format_localized_decimal( wc_format_decimal( $weight, 3, true ) );
	}
}
